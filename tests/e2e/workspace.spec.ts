const browserErrors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const errors: string[] = []
  browserErrors.set(page, errors)
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
})
test.afterEach(async ({ page }) => { expect(browserErrors.get(page)).toEqual([]) })

async function ready(page: Page) {
  await page.goto('/')
  await expect(page).toHaveTitle('MaptelaBridge — Integration Mapping Workspace')
  await expect(page.getByRole('link', { name: 'MaptelaBridge', exact: true })).toBeVisible()
  await expect(page.locator('.monaco-editor')).toHaveCount(2)
  await expect(page.getByText('Valid JSON', { exact: true })).toBeVisible()
  await expect(page.getByText('Valid XML', { exact: true })).toBeVisible()
  await expect(page.getByLabel('INTEGRATION WORKSPACE')).toHaveValue('')
  await expect(page.getByLabel('INTEGRATION WORKSPACE')).toHaveAttribute('placeholder', 'Untitled integration')
  await expect(page.getByLabel('source system name', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('source system name', { exact: true })).toHaveAttribute('placeholder', 'Source System')
  await expect(page.getByLabel('target system name', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('target system name', { exact: true })).toHaveAttribute('placeholder', 'Target System')
}
async function replacePayload(page: Page, side: 'source' | 'target', content: string) {
  const editor = page.locator(`.${side} .monaco-editor`)
  await editor.click({ position: { x: 140, y: 30 } })
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.press('Backspace')
  await page.keyboard.insertText(content)
}
